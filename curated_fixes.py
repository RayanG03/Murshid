def apply_text_fixes(source_name: str, raw: str) -> str:
    """يطبّق قوائم التصحيح الثلاث على نص المصدر قبل تحليله.

    TEXT_FIXES: تصحيحات أعادت النص إلى الصفحة الرسمية (تاريخ، عنوان ناقص).
    OCR_FIXES: كلمات أخطأ الـ OCR (Chandra) في قراءتها: حرف مقروء خطأً («وتقويض» بدل
    «وتفويض»)، أو حرف زائد («اقترتها» بدل «اقرتها»)، أو كلمتان ملتصقتان («القبوللبرامج»).
    ما في وثائق KAU منها طوبق بالـ PDF الأصلي (نصه أو صورة صفحته)؛ لائحة الشؤون الدراسية
    KSU لا PDF لها عندنا، وتصحيحاتها لا تحتمل غير قراءة واحدة من سياقها.
    SPELLING_FIXES: أخطاء إملائية في المصدر نفسه: «ألمخالفة» و«أشرافها» كذلك في صورة
    صفحة لائحة السلوك KAU، والباقي في ملفات نص منسوخ بلا وسوم HTML. تُصحَّح لأن المعنى لا
    يتغيّر، والكلمة الملتصقة أو المقسومة يقرؤها البحث بالكلمات كلمةً أخرى («وجودالمرافق»
    لا تطابق «المرافق»). قرار المستخدم 2026-10-06.
    تُرك عمداً لأنه في الـ PDF نفسه: «بموزونة» (مصطلح دليل التحويل الداخلي KAU) وتكرار
    عنوان «السكن الجامعي». تصحيحات OCR والإملاء لا تُوسم بشارة «نص منقّح يدوياً» لأنها تعيد
    كلمة المصدر ولا تضيف نصاً، وأي نص منها لا يوجد في المصدر يوقف التحليل بخطأ.
    """
    for wrong, right in TEXT_FIXES.get(source_name, []):
        raw = raw.replace(wrong, right)
    for fixes in (OCR_FIXES, SPELLING_FIXES):
        for wrong, right in fixes.get(source_name, []):
            if wrong not in raw:
                raise ValueError(f"التصحيح لم يجد «{wrong}» في {source_name} — تغيّر المصدر")
            raw = raw.replace(wrong, right)
    return raw


def mark_text_fixes(source_name: str, blocks: list[dict]) -> None:
    """يسم الكتلة التي فيها نص صُحح يدوياً، فتظهر شارة «نص منقّح يدوياً» على مقطعها."""
    for _, right in TEXT_FIXES.get(source_name, []):
        for block in blocks:
            if right in block.get("text", ""):
                block["curated"] = True


