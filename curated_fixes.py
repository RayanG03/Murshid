def fix_ksu_calendar(blocks: list[dict]) -> list[dict]:
    """يضع تواريخ الصفحة الرسمية في جداول التقويم ويُكمل حاشية أسبوع التعزيز."""
    tables = []
    for block in blocks:
        if block["t"] == "table":
            tables.append(block)
    if len(tables) != len(KSU_CALENDAR_DATES):
        raise ValueError("عدد جداول تقويم KSU تغيّر — راجع curated_fixes.KSU_CALENDAR_DATES")
    for table, dates in zip(tables, KSU_CALENDAR_DATES):
        if len(table["rows"]) != len(dates):
            raise ValueError("عدد صفوف جدول في تقويم KSU تغيّر — راجع KSU_CALENDAR_DATES")
        for row, (gregorian, hijri) in zip(table["rows"], dates):
            if len(row) != 4:
                raise ValueError("أعمدة جدول تقويم KSU تغيّرت — راجع KSU_CALENDAR_DATES")
            row[2] = gregorian.translate(WESTERN_TO_ARABIC_DIGITS) + " م"
            row[3] = hijri.translate(WESTERN_TO_ARABIC_DIGITS) + " هـ"
        table["curated"] = True
    tables[-1]["header"][0] = KSU_CALENDAR_LAST_TABLE_TITLE
    for block in blocks:
        if block["t"] == "p" and block["text"].startswith(KSU_CALENDAR_NOTE_START):
            block["text"] = KSU_CALENDAR_NOTE
            block["curated"] = True
    return blocks


def find_heading(blocks: list[dict], text: str, start: int) -> int:
    for index in range(start, len(blocks)):
        if blocks[index]["t"] == "h" and blocks[index]["text"] == text:
            return index
    raise ValueError(f"العنوان «{text}» غير موجود — راجع curated_fixes.STALE_SERVICE_SECTIONS")


def remove_stale_sections(blocks: list[dict]) -> list[dict]:
    for start_heading, next_heading in STALE_SERVICE_SECTIONS:
        start = find_heading(blocks, start_heading, 0)
        end = find_heading(blocks, next_heading, start + 1)
        blocks = blocks[:start] + blocks[end:]
    return blocks


def block_line(block: dict) -> str:
    if block["t"] == "table":
        first = block["header"] or (block["rows"][0] if block["rows"] else [])
        return " | ".join(first).strip()
    return block["text"].strip()


def remove_screenshots(source_name: str, blocks: list[dict]) -> list[dict]:
    """يحذف كتل لقطات الشاشة المحددة في SCREENSHOT_SPANS، بالترتيب من أول الوثيقة."""
    start_at = 0
    for start_text, end_text in SCREENSHOT_SPANS.get(source_name, []):
        start = start_at
        while start < len(blocks) and not block_line(blocks[start]).startswith(start_text):
            start += 1
        end = start + 1
        while end < len(blocks) and not block_line(blocks[end]).startswith(end_text):
            end += 1
        if end >= len(blocks):
            raise ValueError(f"لقطة «{start_text}» ← «{end_text}» غير موجودة في {source_name}")
        blocks = blocks[:start] + blocks[end:]
        start_at = start
    return blocks


def restore_riyal(text: str) -> str:
    """رمز الريال في صفحة خدمات KSU صورة سقطت عند الاستخراج وتركت فراغاً بعد الرقم.

    بدونه كتب النموذج «يخصم 10%» والصحيح عشرة ريالات (المصدر: rs.ksu.edu.sa/en/node/1388).
    """
    text = re.sub(r"(\d[\d,]*\)?)\s*(,?)\s{3,}", r"\1 ريال\2 ", text)
    text = text.replace("(4000) .", "(4000) ريال.")
    text = text.replace("الدراسات العليا (900)", "الدراسات العليا (900) ريال")
    return text.replace("قدرها1000", "قدرها 1000 ريال")


